const assert = require('node:assert/strict');
const L = require('../app/learning.js');
const activities = ['easy','moderate','challenging'].map((difficulty,i) => ({ id: 'a'+i, objective: 'o'+i, difficulty }));
const pkg = { packageId: 'unit', activities };
const memory = () => { const map = new Map(); return { getItem: k => map.get(k), setItem: (k,v) => map.set(k,v) }; };
const store = memory();
function event(id,result='correct',extra={}) { return {id,result,timestamp:'2026-10-27T00:00:00Z',durationMs:1000,locale:'en',...extra}; }
assert.equal(L.score({},activities).level,'Starting');
assert.equal(L.score({},[]).percent,0);
assert.equal(L.read({getItem(){throw Error();}},'x').version,undefined);
assert.deepEqual(L.read({getItem:()=>'{broken'},'x'),{});
assert.equal(L.record({getItem:()=>null,setItem(){throw Error();}},pkg,activities[0],event('x')),false);
assert.equal(L.record(store,pkg,activities[0],event('first','incorrect')),true);
L.record(store,pkg,activities[0],event('retry','correct',{retry:true}));
L.record(store,pkg,activities[0],event('retry','correct',{retry:true}));
let saved = L.read(store,'unit');
assert.equal(saved.attempts.length,2,'idempotent submission');
assert.equal(L.score(saved,activities).firstCorrect,0);
assert.equal(L.score(saved,activities).independent,0);
assert.equal(L.score(saved,activities).completed,1);
L.record(store,pkg,activities[0],event('revisit'));
saved = L.read(store,'unit');
assert.equal(L.score(saved,activities).independent,1);
assert.equal(L.score(saved,activities).firstCorrect,0,'first failure immutable');
assert.equal(L.score(saved,activities).percent,12,'recovery credit weighted');
assert.equal(L.score({completed:['a0','unknown'],independent:['a0']},activities).percent,0,'legacy cannot fabricate first evidence');
assert.equal(L.score({completed:['a0','unknown'],independent:['a0']},activities).completed,1);
L.record(store,pkg,activities[1],event('hint','correct',{hint:true}));
L.record(store,pkg,activities[2],event('skip','skip'));
saved = L.read(store,'unit');
assert.equal(L.score(saved,activities).covered,2,'skip not a graded attempt');
assert.equal(L.score(saved,activities).independent,1);
const perfect = memory(); activities.forEach((a,i)=>L.record(perfect,pkg,a,event('p'+i)));
assert.equal(L.score(L.read(perfect,'unit'),activities).level,'Mastered');
const easy = {attempts:[{id:'e',activityId:'a0',result:'correct',assisted:false}]};
const hard = {attempts:[{id:'h',activityId:'a2',result:'correct',assisted:false}]};
assert(L.score(hard,activities).percent > L.score(easy,activities).percent);
const dirty = {attempts:[null,{id:'bad',activityId:'unknown',result:'correct',assisted:false},...hard.attempts,...hard.attempts]};
assert.deepEqual(L.score(dirty,activities),L.score(hard,activities));
const lessons = [{id:'unit',url:'unit/',activityMetadata:activities}];
assert.equal(L.recommend(lessons,{}).reason,'start');
assert.equal(L.recommend(lessons,{unit:saved}).activity.id,'a1');
assert.equal(L.recommend(lessons,{unit:easy}).reason,'continue');
assert.equal(L.recommend(lessons,{unit:L.read(perfect,'unit')}),null);
const frozen = JSON.stringify(saved); L.score(saved,activities); L.recommend(lessons,{unit:saved}); assert.equal(JSON.stringify(saved),frozen);
console.log('Learning unit tests passed: storage, migration, first evidence, assistance, recovery, skips, difficulty, recommendations, purity.');
