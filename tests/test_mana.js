const assert=require('node:assert/strict');
const M=require('../app/mana.js');
const at='2026-11-03T12:00:00';
const answer=(activity,correct=true,assisted=false,when=at,subject='physics')=>({kind:'answer',subject,activity,correct,assisted,at:when});
const step=(s,e)=>{const r=M.reduce(s,e);assert(M.valid(r.state));return r;};
let s=M.fresh();
let r=step(s,answer('a'));assert.equal(r.amount,5);assert.equal(s.ledger.length,0,'pure reducer');s=r.state;
assert.equal(step(s,answer('a')).amount,0,'no repeat farming');
r=step(s,answer('b',false));assert.equal(r.amount,0);s=r.state;
r=step(s,answer('b'));assert.equal(r.amount,3,'mistake persists across visits');s=r.state;
r=step(s,answer('c',true,true));assert.equal(r.amount,3,'free hint reduces first reward only');s=r.state;
assert.equal(step(s,answer('a',true,false,'2026-11-03T20:00:00')).amount,0);
r=step(s,answer('a',true,false,'2026-11-04T12:00:00'));assert.equal(r.amount,2);s=r.state;
assert.equal(step(s,answer('a',true,false,'2026-11-10T12:00:00')).amount,0);
r=step(s,answer('a',true,false,'2026-11-11T12:00:00'));assert.equal(r.amount,2);s=r.state;
assert.equal(step(s,answer('a',true,false,'2026-11-01T12:00:00')).amount,0,'clock rollback cannot mint review');
const set=(subject,allAttempted=true,time=at)=>({kind:'set',subject,allAttempted,at:time});
assert.equal(step(s,set('physics',false)).amount,0);
r=step(s,set('physics'));assert.equal(r.amount,5);s=r.state;
assert.equal(step(s,set('physics')).amount,0);r=step(s,set('maths'));assert.equal(r.amount,5);s=r.state;
assert.equal(step(s,set('physics',true,'2026-11-04T12:00:00')).amount,5);
r=step(s,{kind:'migration',amount:50,at});assert.equal(r.amount,50);s=r.state;
assert.equal(step(s,{kind:'migration',amount:999,at}).amount,0,'one-time carryover');
const before=M.balance(s);r=step(s,{kind:'purchase',item:'forest',at});assert.equal(r.amount,-30);s=r.state;
assert.equal(M.balance(s),before-30);assert(M.owned(s,'forest'));assert.equal(s.equipped,'forest');
assert.equal(step(s,{kind:'purchase',item:'forest',at}).amount,0,'no duplicate charge');
assert.equal(step(s,{kind:'equip',item:'ocean',at}).error,'item');
r=step(s,{kind:'equip',item:'',at});assert.equal(r.state.equipped,'');assert.equal(M.balance(r.state),M.balance(s));
assert.equal(step(M.fresh(),{kind:'purchase',item:'forest',at}).error,'funds');
assert.equal(step(s,answer('new',false)).amount,0,'wrong answers never deduct');
assert.equal(M.reduce({...s,ledger:[{id:'bad',kind:'purchase',amount:-3,at,item:'forest'}]},answer('x')).error,'corrupt');
assert.equal(step(s,{kind:'answer',subject:'unknown',activity:'x',correct:true,assisted:false,at}).error,'event');
assert.equal(step(s,{kind:'migration',amount:-5,at}).amount,0);
const distinct=step(s,answer('a',true,false,at,'maths'));assert.equal(distinct.amount,5,'subjects have distinct reward IDs and a shared total');
console.log('Mana rules passed: purity, first/hint/retry, later-day and seven-day review, clock rollback, daily subject sets, migration, purchases, ownership, insufficient balance, corrupt data and subject isolation.');
