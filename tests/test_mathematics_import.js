const fs=require('node:fs');
const vm=require('node:vm');
const crypto=require('node:crypto');
const assert=require('node:assert/strict');
const html=fs.readFileSync('app/mathematics/index.html','utf8');
const provenance=JSON.parse(fs.readFileSync('app/mathematics/provenance.json','utf8'));
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const context={};
vm.runInNewContext(script.slice(0,script.indexOf('const $='))+';result={practiceQuestionBanks,practiceFinalQuestions,notes,checkpoints,noteMaterials,evaluationQuestions,form4,form5};',context);
const content=JSON.stringify(context.result);
assert.equal(crypto.createHash('sha256').update(content).digest('hex'),provenance.contentSha256,'all upstream mathematics content retained');
const d=context.result;
assert.deepEqual(Array.from(d.practiceQuestionBanks,bank=>bank.length),[8,8,8]);
assert.equal(d.practiceFinalQuestions.length,5);
assert.equal(d.notes.length,3);assert.equal(d.noteMaterials.length,3);assert.equal(d.checkpoints.length,3);assert.equal(d.evaluationQuestions.length,3);
assert.deepEqual(Array.from(d.evaluationQuestions,q=>q.correct),[0,1,1]);
assert.equal((html.match(/window\.localStorage/g)||[]).length,3,'only namespaced adapter accesses browser storage');
assert(html.includes('"haha:math:v1:" + key'));
assert(!/\b(?:fetch\(|XMLHttpRequest|WebSocket)/.test(script),'no live tutor or unconnected network calls');
assert(!/appgprj_|sk-proj-|sk_live_/.test(html),'no original hosting identity or API credentials');
assert(html.includes('href="../index.html#subjects"'));
assert(!html.includes('data-action="friends">Friends'));
console.log('Mathematics import passed: all upstream content preserved, 24 practice questions, five capstones, notes/checks/evaluation, namespace adapter, no external service or owner hosting identity.');
